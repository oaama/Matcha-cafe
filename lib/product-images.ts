export function defaultProductImage(productId: string): string | undefined {
  return PRODUCT_IMAGE_IDS.has(productId) ? `/menu/${productId}.webp` : undefined;
}

export function withProductImage<T extends Pick<Product, 'id' | 'image'>>(product: T): T {
  if (product.image) return product;
  const image = defaultProductImage(product.id);
  return image ? { ...product, image } : product;
}
